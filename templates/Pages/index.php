<!-- JavaScript to Handle Dynamic Video and Name -->
<script>
document.addEventListener("DOMContentLoaded", function () {
    const videoModal = document.getElementById("videoModal");
    const videoElement = document.getElementById("modal-video");
    const videoSource = document.getElementById("video-source");
    const modalTitle = document.getElementById("videoModalLabel");

    videoModal.addEventListener("show.bs.modal", function (event) {
        const trigger = event.relatedTarget; // The clicked anchor tag
        const videoUrl = trigger.getAttribute("data-video");
        const videoTitle = trigger.getAttribute("data-name");

        if (videoUrl) {
            videoSource.src = videoUrl;
            videoElement.load(); // Load new video
            modalTitle.textContent = videoTitle; // Update modal title
        }
    });

    videoModal.addEventListener("hidden.bs.modal", function () {
        videoElement.pause(); // Stop video playback when modal closes
    });
});
</script>